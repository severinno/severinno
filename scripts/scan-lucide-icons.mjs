#!/usr/bin/env node

/**
 * scan-lucide-icons.mjs
 *
 * Scans all .tsx files under src/components/vitrine/ (including __tests__/*.tsx),
 * extracts all named imports from `lucide-react`, and prints a ready-to-copy
 * `vi.mock("lucide-react", …)` block sorted alphabetically.
 *
 * Usage:
 *   node scripts/scan-lucide-icons.mjs            # dry run — print to stdout
 *   node scripts/scan-lucide-icons.mjs --save     # overwrite vitrine-a11y-setup.tsx
 *   npm run scan-icons                            # dry run — print to stdout
 *
 * Ignores:
 *   - import * as …  (namespace imports — can't extract individual names)
 *   - type-only specifiers (import { type Foo })
 *   - node_modules, .next, dist, etc.
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs"
import { join, relative, resolve } from "node:path"

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

const ROOT = resolve(import.meta.dirname, "..")
const SCAN_DIR = join(ROOT, "src", "components", "vitrine")
const SETUP_FILE = join(ROOT, "src", "components", "vitrine", "__tests__", "vitrine-a11y-setup.tsx")

// ---------------------------------------------------------------------------
// File discovery
// ---------------------------------------------------------------------------

/** Recursively collect all .tsx files under a directory. */
function collectTsxFilesSync(dir) {
  const results = []

  const entries = readdirSync(dir, { withFileTypes: true })
  for (const entry of entries) {
    const fullPath = join(dir, entry.name)
    if (entry.name === "node_modules") continue
    if (entry.name.startsWith(".")) continue

    if (entry.isDirectory()) {
      results.push(...collectTsxFilesSync(fullPath))
    } else if (entry.isFile() && entry.name.endsWith(".tsx")) {
      results.push(fullPath)
    }
  }
  return results
}

// ---------------------------------------------------------------------------
// Import extraction
// ---------------------------------------------------------------------------

/**
 * Regex that matches import statements from "lucide-react".
 * Captures everything between the outer braces, across multiple lines.
 *
 * Examples matched:
 *   import { MapPin } from "lucide-react"
 *   import { MapPin, Loader2 } from 'lucide-react'
 *   import {
 *     MapPin,
 *     type LucideIcon,
 *     Loader2,
 *   } from "lucide-react"
 */
const IMPORT_RE = /import\s*\{([^}]+)\}\s*from\s*["']lucide-react["']/g

/**
 * Extract unique icon names from a file's content.
 * Filters out:
 *   - `type ...` specifiers
 *   - Whitespace-only entries
 *   - Aliased imports (`Foo as Bar` → we keep Foo)
 */
function extractIcons(content) {
  const icons = new Set()

  for (const match of content.matchAll(IMPORT_RE)) {
    const block = match[1]

    // Split by comma and clean each specifier
    const specifiers = block
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean)

    for (const spec of specifiers) {
      // Skip type-only specifiers: "type LucideIcon", "type  LucideIcon"
      if (/^type\s/.test(spec)) continue

      // Handle aliases: "Foo as Bar" → use "Foo"
      const name = spec.split(/\s+as\s+/)[0].trim()
      if (name && /^[A-Z][A-Za-z0-9]*$/.test(name)) {
        icons.add(name)
      }
    }
  }

  return icons
}

// ---------------------------------------------------------------------------
// Mock block generator
// ---------------------------------------------------------------------------

/**
 * Generate the full `vi.mock("lucide-react", …)` block.
 * Icons are sorted alphabetically.
 */
function generateMockBlock(icons) {
  const sorted = [...icons].sort((a, b) => a.localeCompare(b))

  const entries = sorted.map((name) => `    ${name}: Icon,`).join("\n")

  return `/**
 * vitrine-a11y-setup — provides a comprehensive lucide-react mock with all
 * icons used across src/components/vitrine/ components.
 *
 * AUTO-GENERATED by \`scripts/scan-lucide-icons.mjs\`.
 * Re-generate with: \`npm run scan-icons\` or \`node scripts/scan-lucide-icons.mjs --save\`.
 */
import { vi } from "vitest"
import React from "react"

vi.mock("lucide-react", () => {
  const Icon = (p: any) => <svg aria-hidden="true" {...p} />
  Icon.displayName = "LucideIcon"
  return {
${entries}
  }
})
`
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function main() {
  const args = process.argv.slice(2)
  const shouldSave = args.includes("--save")
  const shouldCheck = args.includes("--check")

  // 1. Collect all .tsx files
  const allFiles = collectTsxFilesSync(SCAN_DIR).filter(
    (f) => !f.includes("vitrine-a11y-setup.tsx"),
  )
  console.error(`📁 Scanned ${allFiles.length} .tsx files in ${relative(ROOT, SCAN_DIR)}`)

  // 2. Extract unique icons
  const allIcons = new Set()
  const fileIcons = [] // for reporting

  for (const file of allFiles) {
    try {
      const content = readFileSync(file, "utf-8")
      const icons = extractIcons(content)
      if (icons.size > 0) {
        fileIcons.push({ file: relative(ROOT, file), icons: [...icons].sort() })
        for (const icon of icons) allIcons.add(icon)
      }
    } catch {
      // skip files that can't be read (shouldn't happen, but be safe)
    }
  }

  // 3. Report
  console.error(`🔍 Found ${allIcons.size} unique lucide-react icons:\n`)
  for (const { file, icons } of fileIcons) {
    console.error(`   ${file} → ${icons.join(", ")}`)
  }

  // 4. Generate the mock block
  const generated = generateMockBlock(allIcons)

  // 5. Action based on flags
  if (shouldCheck) {
    // --check mode: compare generated with current file content
    let current = ""
    try {
      current = readFileSync(SETUP_FILE, "utf-8")
    } catch {
      // file doesn't exist yet
    }
    if (generated === current) {
      console.error(`\n✅ ${relative(ROOT, SETUP_FILE)} is up to date`)
      process.exit(0)
    } else {
      console.error(`\n❌ ${relative(ROOT, SETUP_FILE)} is OUTDATED!`)
      console.error(`   Run "npm run scan-icons:save" to regenerate it.`)
      process.exit(1)
    }
  } else if (shouldSave) {
    writeFileSync(SETUP_FILE, generated, "utf-8")
    console.error(`\n💾 Saved to ${relative(ROOT, SETUP_FILE)}`)
  } else {
    // Dry run — print to stdout
    console.log(generated)
    console.error(`\n📋 Dry run — add --save to overwrite ${relative(ROOT, SETUP_FILE)} in place`)
  }
}

main()
