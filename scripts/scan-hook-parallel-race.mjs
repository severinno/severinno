#!/usr/bin/env node
/**
 * scan-hook-parallel-race.mjs - guard de ESTABILIDADE do par paralelo
 * lint-staged | tsc do pre-commit (secao 11.8 do gates-proofs.md).
 *
 * WHY: a 11.8 ADOTOU o paralelo com nota - a janela de raca (eslint --fix
 * reescreve um arquivo staged ENQUANTO o tsc --noEmit le os mesmos
 * arquivos -> erro TS transitorio) e estreita mas NAO e zero, e a amostra
 * da medicao foi ~6 runs. Este guard roda o par REAL N vezes (default 10)
 * num job dedicado de CI e FALHA se qualquer erro TS transitorio aparecer
 * - provando a estabilidade do ADOTADO (ou sinalizando a reversao para o
 * sequencial quando a janela materializar).
 *
 * COMO A RACA E EXERCITADA: o lint-staged so processa arquivos STAGED, e o
 * CI tem checkout fresco sem nada staged - sem probe, o par rodaria sem
 * nenhuma reescrita e a janela seria ZERO (prova vacua). O guard cria um
 * PROBE com uma violacao FIXABLE (let -> const via prefer-const, provada
 * empiricamente 2026-08), faz git add do probe, e em CADA iteracao
 * re-injeta a violacao + re-stages - o lint-staged reescreve o probe
 * enquanto o tsc le, reproduzindo a condicao da raca de verdade.
 *
 * FLUXO:
 *   1. Baseline: roda o tsc SOZINHO (sem lint concorrente). Se falhar, o
 *      repo TEM um erro TS real (nao e a raca) - o guard reporta e sai 1
 *      com mensagem distinta (nao confunde erro real com raca).
 *   2. Loop N: re-escreve o probe com a violacao + git add, roda o par
 *      exatamente como o hook (lint em background primeiro, tsc em
 *      foreground, wait no lint), registra tsc/lint exit + se o probe foi
 *      reescrito (probeFixed).
 *   3. Verdict: baseline falhou -> 1; qualquer lint exit != 0 -> 1 (o par
 *      quebraria o hook); probe NUNCA fixado -> 1 (a janela nao foi
 *      exercitada - wiring quebrado, prova vacua); qualquer tsc exit != 0
 *      com baseline 0 -> TRANSIENTE (a raca materializou) -> 1; tudo 0 ->
 *      0 "race-stable".
 *
 * CLEANUP (finally): remove o probe + git reset (unstage) - o CI e
 * efemero, mas uma rodada local nao pode deixar lixo no index.
 *
 * Env overrides (testes hermeticos - espelha o FRAGILE_SCAN_ROOT):
 *   PARALLEL_RACE_ITERATIONS  (default 10)
 *   PARALLEL_RACE_ROOT        (root do repo; default cwd)
 *   PARALLEL_RACE_TSC_CMD     (default "bun run typecheck")
 *   PARALLEL_RACE_LINT_CMD    (default "bun x lint-staged")
 *   PARALLEL_RACE_PROBE_REL   (probe relativo ao root; default
 *                              e2e/__race_probe__.ts)
 *   PARALLEL_RACE_SKIP_GIT    ("1" pula git add/reset - repos sinteticos)
 *
 * CLI: node scripts/scan-hook-parallel-race.mjs [--iterations N]
 *   (N tambem via env PARALLEL_RACE_ITERATIONS; default 10)
 *
 * API importavel (entry-point guarded): parseIterations, probeContent,
 * isProbeFixed, detectTransient. Saida ASCII pura (gate file). Puro node,
 * sem deps - apenas child_process/fs/path.
 */
import { spawn } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

/**
 * Resolve o numero de iteracoes: flag --iterations N > env > default 10.
 * Exportada para os testes hermeticos.
 */
export function parseIterations(args = [], env = process.env) {
  const idx = args.indexOf("--iterations")
  if (idx !== -1 && args[idx + 1]) {
    const n = Number.parseInt(args[idx + 1], 10)
    if (Number.isFinite(n) && n > 0) return n
  }
  const envN = Number.parseInt(env.PARALLEL_RACE_ITERATIONS || "", 10)
  if (Number.isFinite(envN) && envN > 0) return envN
  return 10
}

/**
 * Conteudo do probe: TS valido nos DOIS estados (let e const) - o tsc nao
 * pode ter erro LEGITIMO no probe (senao o baseline confundiria a raca).
 * prefer-const (fixable) reescreve let -> const (provado empiricamente
 * 2026-08 com o shim real). ASCII puro (gate file).
 */
export function probeContent() {
  return [
    "// race probe (generated by scan-hook-parallel-race.mjs - ASCII pure)",
    "let raceProbeValue = 1",
    "export { raceProbeValue }",
    "",
  ].join("\n")
}

/**
 * O probe foi reescrito pelo lint-staged? (let -> const). Um probe que
 * continua com `let` significa que a janela de raca NAO foi exercitada.
 */
export function isProbeFixed(content) {
  return !content.includes("let raceProbeValue") && content.includes("const raceProbeValue")
}

/**
 * Runs do par onde o tsc falhou COM o baseline verde - a assinatura da
 * raca (erro TS transitorio). Com baseline vermelho, o resultado e
 * "erro TS real do repo", nao raca - retorna [] (o caller reporta o
 * baseline separado). Exportada para os testes hermeticos.
 */
export function detectTransient(runs, baselineExit) {
  if (baselineExit !== 0) return []
  return runs.filter((r) => r.tscExit !== 0).map((r) => r.run)
}

/** Roda um comando via shell e resolve com o exit code (promise). */
function runCmd(cmd, cwd) {
  return new Promise((resolve) => {
    let child
    try {
      child = spawn(cmd, { shell: true, cwd, stdio: ["ignore", "pipe", "pipe"] })
    } catch {
      resolve(-1)
      return
    }
    let err = ""
    child.stderr.on("data", (d) => (err += d))
    child.on("error", () => resolve(-1))
    child.on("close", (code) => resolve({ code: code ?? -1, err }))
  })
}

/**
 * Roda o par exatamente como o hook: lint em BACKGROUND primeiro (o fix de
 * ~1s cai antes de o tsc ler a maioria dos arquivos - estreita a janela),
 * tsc em FOREGROUND, wait no lint. Retorna { lintExit, tscExit, lintErr,
 * tscErr } - o stderr do tsc alimenta o verdict de transient (a evidencia
 * do REVERT: erro de parse real vs OOM vs raca de escrita, a classe que a
 * secao 11.8 promete diagnosticar).
 */
async function runPair({ lintCmd, tscCmd, cwd }) {
  const lintP = runCmd(lintCmd, cwd)
  const tsc = await runCmd(tscCmd, cwd)
  const lint = await lintP
  return { lintExit: lint.code, tscExit: tsc.code, lintErr: lint.err, tscErr: tsc.err }
}

/** git add do probe (falha = staging impossivel = a raca nao pode ser exercitada). */
function gitAdd(root, probeRel) {
  return new Promise((resolve) => {
    const child = spawn("git", ["add", "--", probeRel], {
      cwd: root,
      stdio: ["ignore", "pipe", "pipe"],
    })
    child.on("error", () => resolve(-1))
    child.on("close", (code) => resolve(code ?? -1))
  })
}

/** git reset do probe (unstage no cleanup). */
function gitReset(root, probeRel) {
  return new Promise((resolve) => {
    const child = spawn("git", ["reset", "-q", "--", probeRel], {
      cwd: root,
      stdio: ["ignore", "pipe", "pipe"],
    })
    child.on("error", () => resolve(-1))
    child.on("close", (code) => resolve(code ?? -1))
  })
}

async function main() {
  const args = process.argv.slice(2)
  const root = path.resolve(process.env.PARALLEL_RACE_ROOT || process.cwd())
  const iterations = parseIterations(args)
  const tscCmd = process.env.PARALLEL_RACE_TSC_CMD || "bun run typecheck"
  const lintCmd = process.env.PARALLEL_RACE_LINT_CMD || "bun x lint-staged"
  const probeRel = process.env.PARALLEL_RACE_PROBE_REL || "e2e/__race_probe__.ts"
  const skipGit = process.env.PARALLEL_RACE_SKIP_GIT === "1"
  const probe = path.join(root, probeRel)

  fs.mkdirSync(path.dirname(probe), { recursive: true })
  fs.writeFileSync(probe, probeContent())

  let gitOk = true
  if (!skipGit) {
    gitOk = (await gitAdd(root, probeRel)) === 0
    if (!gitOk) {
      fs.rmSync(probe, { force: true })
      console.error(
        `parallel-race: git add do probe falhou (${probeRel}) - sem arquivo staged o lint-staged nao reescreve nada e a janela de raca nao pode ser exercitada (prova vacua)`,
      )
      return 2
    }
  }

  try {
    // 1. BASELINE: tsc sozinho (sem lint concorrente).
    const baseline = await runCmd(tscCmd, root)
    const baselineExit = baseline.code
    if (baselineExit !== 0) {
      console.error(
        `parallel-race: BASELINE tsc FAILED (exit ${baselineExit}) - o repo tem um erro TS REAL, nao e a raca; corrija o erro de tipo primeiro (o par paralelo nao tem culpa)`,
      )
      // Simetria com o verdict de transient: surface o stderr do tsc para o
      // erro real ser diagnosticavel no log do CI sem run local.
      console.error(`parallel-race:   baseline tsc stderr: ${baseline.err.trim() || "(sem stderr)"}`)
      return 1
    }
    console.log(`parallel-race: baseline tsc ok (exit 0)`)

    // 2. LOOP N: re-injeta a violacao + re-stage + roda o par.
    const runs = []
    for (let i = 1; i <= iterations; i++) {
      fs.writeFileSync(probe, probeContent()) // re-injeta a violacao
      if (!skipGit) await gitAdd(root, probeRel) // re-stages o probe sujo
      const pair = await runPair({ lintCmd, tscCmd, cwd: root })
      let fixed = false
      try {
        fixed = isProbeFixed(fs.readFileSync(probe, "utf8"))
      } catch {
        fixed = false
      }
      runs.push({ run: i, ...pair, probeFixed: fixed })
      const tag = pair.lintExit === 0 && pair.tscExit === 0 && fixed ? "ok" : "FAIL"
      console.log(
        `parallel-race: run ${i}/${iterations}: tsc=${pair.tscExit} lint=${pair.lintExit} probeFixed=${fixed} ${tag}`,
      )
    }

    // 3. VERDICT.
    const transient = detectTransient(runs, baselineExit)
    const lintBroken = runs.filter((r) => r.lintExit !== 0)
    const neverFixed = runs.every((r) => !r.probeFixed)

    if (lintBroken.length > 0) {
      for (const r of lintBroken) {
        console.error(
          `parallel-race: lint-staged FAILED no run ${r.run} (exit ${r.lintExit}) - o par quebraria o hook; mensagem: ${r.lintErr.trim() || "(sem stderr)"}`,
        )
      }
      return 1
    }
    if (neverFixed) {
      console.error(
        "parallel-race: probe NUNCA foi reescrito pelo lint-staged em nenhum run - a janela de raca nao foi exercitada (wiring do probe quebrado? prefer-const desabilitado?); prova vacua, nao valida a estabilidade",
      )
      return 1
    }
    if (transient.length > 0) {
      console.error(
        `parallel-race: TRANSIENT TS ERROR em run(s) [${transient.join(", ")}] - a janela de raca da secao 11.8 MATERIALIZOU: eslint --fix reescreveu um arquivo enquanto o tsc o lia. REVERTA o bloco paralelo do .husky/pre-commit para o 'bun run typecheck' sequencial (recipe da 11.5) e atualize a secao 11.8 com a evidencia`,
      )
      // A evidencia do REVERT: o stderr do tsc dos runs afetados (erro de
      // parse real vs OOM vs raca de escrita) - sem ele a decisao seria
      // cega. Reproduzir o erro depende do run; o texto abaixo e o
      // diagnostico bruto capturado no momento.
      for (const r of runs.filter((x) => x.tscExit !== 0)) {
        console.error(`parallel-race:   tsc stderr (run ${r.run}): ${r.tscErr.trim() || "(sem stderr)"}`)
      }
      return 1
    }
    console.log(
      `parallel-race: race-stable: ${iterations}/${iterations} runs do par limpos (baseline tsc ok, tsc exit 0 em todos, probe reescrito em todos) - secao 11.8 ADOTADO estavel nesta amostra`,
    )
    return 0
  } finally {
    // CLEANUP: remove o probe + unstage (CI efemero; rodada local limpa).
    try {
      if (!skipGit) await gitReset(root, probeRel)
    } catch {
      /* best-effort */
    }
    try {
      fs.rmSync(probe, { force: true })
    } catch {
      /* best-effort */
    }
  }
}

// Entry-point guard: so roda o CLI quando executado diretamente (o vitest
// importa as funcoes puras sem side effects).
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main()
}
